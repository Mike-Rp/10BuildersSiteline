import assert from "node:assert/strict"
import test from "node:test"
import { JSDOM } from "jsdom"
import { createServer } from "vite"

test("admin inquiry log and form show grouped controls, phone formats, and the routing preview", { timeout: 60000 }, async t => {
  const { window } = new JSDOM('<div id="root"></div>', { url: "http://localhost", pretendToBeVisual: true })
  const globals = new Map()
  let clientSearch = "match"
  let submissionCalls = 0
  const clients = [
    { id: "company-1", source: "account", client_type: "company", client_name: "Example Construction Company", company_name: "Example Construction Company", primary_contact: "Maria Santos", designation: "Manager", email: "company@example.com", phone: "+639987328173" },
    { id: "person-2", source: "inquiry", client_type: "individual", client_name: "Juan Cruz", company_name: "", primary_contact: "", designation: "", email: "juan@example.com", phone: "09123456789" },
  ]
  for (const [key, value] of Object.entries({
    window, document: window.document, HTMLElement: window.HTMLElement, Node: window.Node, IS_REACT_ACT_ENVIRONMENT: true,
    fetch: async (url, init) => {
      if (init?.method === "POST" && String(url).endsWith("/projects/inquiries")) {
        submissionCalls++
        await new Promise(resolve => setTimeout(resolve, 20))
        return Response.json({ message: "Review submission test failure" }, { status: 503 })
      }
      return String(url).includes("/inquiries/clients?")
      ? clientSearch === "error" ? Response.json({ message: "Search unavailable" }, { status: 503 }) : Response.json({ data: clientSearch === "empty" ? [] : clients })
      : Response.json({ data: String(url).includes("opm-candidates?project_type=Residential")
      ? [{ id: "preferred", name: "Avery Reyes", experience_years: 10 },
        { id: "second", name: "Jordan Santos", experience_years: 8 },
        { id: "third", name: "Sam Cruz", experience_years: 6 },
        { id: "fourth", name: "Alex Ramos", experience_years: 4 }] : [] }) },
  })) {
    globals.set(key, Object.getOwnPropertyDescriptor(globalThis, key))
    Object.defineProperty(globalThis, key, { value, configurable: true, writable: true })
  }
  const server = await createServer({ server: { middlewareMode: true, hmr: false, watch: null }, appType: "custom", logLevel: "silent", optimizeDeps: { noDiscovery: true, include: [] } })
  const { default: React, act } = await import("react")
  const { createRoot } = await import("react-dom/client")
  const root = createRoot(document.getElementById("root"))
  t.after(async () => {
    await act(() => root.unmount())
    await server.close()
    window.close()
    for (const [key, descriptor] of globals) {
      if (descriptor) Object.defineProperty(globalThis, key, descriptor)
      else delete globalThis[key]
    }
  })
  const { default: ProjectInquiries } = await server.ssrLoadModule("/src/ProjectInquiries.tsx")
  await act(() => root.render(React.createElement(ProjectInquiries, { role: "admin", onReload() {} })))
  assert.equal(document.querySelectorAll(".inquiry-log-tabs button").length, 4)
  assert.ok(document.querySelector(".inquiry-log-tabs + .inquiry-log-filters"))
  const button = name => [...document.querySelectorAll("button")].find(item => item.textContent.trim() === name)
  await act(() => button("New project inquiry").click())
  await act(() => document.querySelector('[name="inquiry-client-record"][value="new"]').click())
  await act(() => document.querySelector('[name="inquiry-client-type"][value="individual"]').click())
  await act(() => button("Next: Client details").click())
  assert.ok(document.querySelector('input[placeholder="Lastname, FirstName"]'))
  const phone = document.querySelector('input[type="tel"]')
  const setPhone = value => act(() => {
    Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, "value").set.call(phone, value)
    phone.dispatchEvent(new window.Event("input", { bubbles: true }))
  })
  assert.equal(document.querySelector(".mobile-number-prefix").textContent, "+63")
  assert.equal(phone.getAttribute("aria-invalid"), null, "untouched empty mobile stays quiet")
  assert.match(document.querySelector(".inquiry-mobile-counter").textContent, /0\/10/)
  await setPhone("123")
  assert.equal(phone.value, "123")
  assert.match(document.querySelector("#inquiry-phone-notice").textContent, /start with 9/)
  for (const invalid of ["123A4", "123 4", "123-4", "123+4", "１２３", "12345678901"]) {
    await setPhone(invalid)
    assert.equal(phone.value, "123", "non-digits and more than ten digits are rejected")
    assert.equal(document.querySelector(".inquiry-mobile-counter").textContent, "3/10")
  }
  assert.doesNotMatch(document.querySelector("#inquiry-phone-notice").textContent, /numbers only/i)
  await setPhone("912")
  await act(() => button("Next: Project details").click())
  assert.ok(document.querySelector(".inquiry-client-details-step"), "incomplete number prevents progression")
  assert.match(document.querySelector("#inquiry-phone-notice").textContent, /all 10/)
  assert.equal(phone.maxLength, 10)
  assert.match(phone.getAttribute("aria-describedby"), /phone-notice/)
  const paste = new window.Event("paste", { bubbles: true, cancelable: true })
  Object.defineProperty(paste, "clipboardData", { value: { getData: () => "+639123456789" } })
  await act(() => phone.dispatchEvent(paste))
  assert.equal(phone.value, "9123456789")
  assert.equal(phone.getAttribute("aria-invalid"), null)
  assert.equal(document.querySelector(".inquiry-mobile-counter").textContent, "10/10")
  assert.equal(phone.checkValidity(), true)
  for (const formatted of ["09987328173", "+63 998 732 8173", "639987328173", "9987328173"]) {
    const event = new window.Event("paste", { bubbles: true, cancelable: true })
    Object.defineProperty(event, "clipboardData", { value: { getData: () => formatted } })
    await act(() => phone.dispatchEvent(event))
    assert.equal(phone.value, "9987328173", `paste normalizes ${formatted}`)
    assert.equal(phone.checkValidity(), true)
  }
  await act(() => phone.dispatchEvent(paste))
  await act(() => {
    for (const [selector, value] of [['[aria-label="Client name"]', 'Maria Santos'], ['[aria-label="Contact email address"]', 'maria@example.com']]) {
      const input = document.querySelector(selector)
      Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, "value").set.call(input, value)
      input.dispatchEvent(new window.Event("input", { bubbles: true }))
    }
  })
  await act(() => button("Next: Project details").click())
  const measurements = document.querySelector(".admin-inquiry-measurements")
  assert.equal(measurements.querySelectorAll('input[inputmode="decimal"]').length, 2)
  assert.equal(measurements.querySelectorAll('input[inputmode="numeric"]').length, 1)
  assert.match(measurements.textContent, /Lot area/)
  assert.doesNotMatch(measurements.textContent, /Land area/i)
  const [lotInput, totalInput] = measurements.querySelectorAll('input[inputmode="decimal"]')
  const floorInput = measurements.querySelector('input[name="floor_count"]')
  const enterMeasurement = (input, value) => act(() => {
    Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, "value").set.call(input, value)
    input.dispatchEvent(new window.Event("input", { bubbles: true }))
  })
  assert.equal(measurements.querySelector('[aria-invalid="true"]'), null, "untouched measurements stay quiet")
  const validity = async input => { let valid; await act(() => { valid = input.checkValidity() }); return valid }
  await enterMeasurement(lotInput, "00020.50")
  assert.equal(lotInput.value, "20.50", "area normalizes only leading zeros, preserving decimal precision")
  await enterMeasurement(floorInput, "002")
  assert.equal(floorInput.value, "2")
  await enterMeasurement(totalInput, "0001000.25")
  assert.equal(totalInput.value, "1,000.25", "formatting retains accepted digits and decimal places")
  await enterMeasurement(lotInput, "000")
  assert.equal(lotInput.value, "0", "zero remains visible and invalid rather than becoming an empty field")
  await enterMeasurement(lotInput, "")
  assert.equal(lotInput.value, "")
  await enterMeasurement(lotInput, "19.99")
  assert.equal(await validity(lotInput), false)
  assert.equal(lotInput.getAttribute("aria-invalid"), "true")
  await enterMeasurement(floorInput, "201")
  assert.equal(await validity(floorInput), false)
  assert.equal(floorInput.getAttribute("aria-invalid"), "true")
  await enterMeasurement(floorInput, "1.5")
  assert.equal(await validity(floorInput), false)
  await enterMeasurement(totalInput, "10")
  assert.equal(totalInput.getAttribute("aria-invalid"), null, "positive totals have no independent minimum")
  await enterMeasurement(totalInput, "100")
  assert.equal(document.querySelector('#inquiry-floor-area-range'), null, "invalid prerequisites do not show a calculated range")
  assert.equal(totalInput.getAttribute("aria-invalid"), null, "dependent range errors stay hidden until prerequisites are valid")
  await enterMeasurement(lotInput, "200")
  await enterMeasurement(floorInput, "2")
  await enterMeasurement(totalInput, "399.99")
  assert.equal(await validity(totalInput), true, "a positive average below the lot area can proceed")
  await enterMeasurement(totalInput, "400")
  assert.equal(await validity(totalInput), true)
  assert.match(document.querySelector('#inquiry-floor-area-range').textContent, /Maximum total: 400/)
  assert.match(document.querySelector('.inquiry-average-summary').textContent, /Average floor area.*200.*m² per floor/)
  await act(() => document.querySelector('[aria-label="How total floor area is calculated"]').click())
  assert.match(document.querySelector('.intake-info-panel').textContent, /Each floor must fit within the lot area/)
  await act(() => document.querySelector('[aria-label="Close help: Floor area calculation"]').click())
  await enterMeasurement(totalInput, "400.01")
  assert.equal(await validity(totalInput), false)
  assert.match(document.querySelector('#inquiry-floor_area_sqm-error').textContent, /must not exceed 400/)
  await enterMeasurement(lotInput, "800")
  await enterMeasurement(floorInput, "5")
  await enterMeasurement(totalInput, "3000")
  assert.equal(await validity(totalInput), true)
  assert.equal(measurements.querySelectorAll('input[inputmode="decimal"]').length, 2)
  assert.doesNotMatch(measurements.textContent, /Ground-floor footprint|Site occupancy/)
  await act(() => document.querySelector('input[name="inquiry-project-type"][value="Residential"]').click())
  assert.match(document.querySelector(".admin-inquiry-opm-preview li:first-child").textContent, /Avery Reyes.*Best match/)
  assert.match(document.querySelector(".admin-inquiry-opm-preview li:last-child").textContent, /Sam Cruz/)
  assert.equal(document.querySelectorAll(".admin-inquiry-opm-preview li").length, 3)
  assert.equal(document.querySelector(".admin-inquiry-opm-preview li input, .admin-inquiry-opm-preview li button"), null)
  await act(() => document.querySelector('input[name="inquiry-classification"][value="Urgent"]').click())
  await act(() => document.querySelectorAll('input[name="immediate-consultation"]')[1].click())
  assert.equal(document.querySelector(".admin-inquiry-classification").disabled, true)
  assert.equal(document.querySelector('input[name="inquiry-classification"]:checked').value, "Normal")
  assert.match(document.querySelector(".admin-inquiry-consultation").textContent, /within one working day/)
  for (const [selector, value] of [['input[placeholder="Maple Residence"]', 'Test inquiry'], ['input[placeholder="Location"]', 'Test location']]) {
    await enterMeasurement(document.querySelector(selector), value)
  }
  await act(() => button("Next: Review").click())
  assert.equal(submissionCalls, 0, "Next opens Review without submitting or assigning an OPM")
  assert.equal(submissionCalls, 0, "Next opens review without posting")
  assert.ok(document.querySelector('.inquiry-review-step'))
  await act(async () => { button("Submit inquiry").click(); button("Submit inquiry").click(); await new Promise(resolve => setTimeout(resolve, 40)) })
  assert.equal(submissionCalls, 1, "rapid submission cannot post twice")
  assert.ok(document.querySelector('.inquiry-review-step'), "failure retains review")
  assert.match(document.querySelector('.inquiry-review-step').textContent, /Review submission test failure/)
  assert.match(document.querySelector(".inquiry-fields").textContent, /\+639123456789/, "review retains the complete international number")
  await act(() => button("Previous").click())
  await act(() => button("Previous").click())
  assert.equal(document.querySelector('input[type="tel"]').value, "9123456789", "Previous preserves the number")
  await act(() => document.querySelector('[aria-label="Close dialog"]').click())
  assert.ok(document.querySelector('[aria-label="Save this inquiry as a draft?"]'), "close still protects the inquiry draft")
  await act(() => button("Keep editing").click())
  assert.ok(document.querySelector(".inquiry-client-details-step"))

  const { default: InquiryClientFields } = await server.ssrLoadModule("/src/InquiryClientFields.tsx")
  for (const savedPhone of ["+639987328173", "09987328173"]) {
    const saved = { client_record: "existing", client_type: "company", company_name: "Example Company", primary_contact: "Maria Santos", email: "maria@example.com", phone: savedPhone }
    let changed = false
    await act(() => root.render(React.createElement(InquiryClientFields, { key: savedPhone, page: "details", details: saved, onChange: () => { changed = true }, disabled: false })))
    assert.equal(document.querySelector('input[type="tel"]').value, "9987328173")
    assert.equal(document.querySelector('input[type="tel"]').disabled, true)
    assert.equal(document.querySelector('[aria-label="Company name"]').readOnly, true)
    assert.match(document.querySelector(".inquiry-client-details-heading").textContent, /Company \/ organization · Existing client/)
    assert.ok(document.querySelector('input[type="checkbox"][required]'))
    assert.equal(changed, false, "rendering existing records must never rewrite their saved format")
  }
  await act(() => root.render(React.createElement(ProjectInquiries, { key: "path-check", role: "admin", onReload() {} })))
  await act(() => button("New project inquiry").click())
  assert.equal(button("Next: Client details").disabled, true, "default selection policy is preserved")
  await act(() => document.querySelector('[name="inquiry-client-record"][value="new"]').click())
  await act(() => document.querySelector('[name="inquiry-client-type"][value="company"]').click())
  await act(() => button("Next: Client details").click())
  assert.ok(document.querySelector('[aria-label="Company name"]'))
  await act(() => button("Previous").click())
  assert.equal(document.querySelector('[name="inquiry-client-type"][value="company"]').checked, true)
  await act(() => document.querySelector('[name="inquiry-client-record"][value="existing"]').click())
  assert.equal(document.querySelector('[name="inquiry-client-type"]'), null)
  assert.equal(button("Next: Client details").disabled, true)
  await act(() => document.querySelector('#admin-inquiry-form').dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true })))
  assert.match(document.querySelector('.inquiry-path-error').textContent, /Select an existing client/)
  assert.equal(document.querySelector('.inquiry-client-details-step'), null, "form submission cannot bypass required client selection")
  const search = () => document.querySelector('[aria-label="Find an existing client"]')
  const searchFor = value => act(() => {
    Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, "value").set.call(search(), value)
    search().dispatchEvent(new window.Event("input", { bubbles: true }))
  })
  await searchFor("Example")
  assert.match(document.querySelector('#inquiry-client-search-status').textContent, /Searching clients/)
  await act(() => new Promise(resolve => setTimeout(resolve, 350)))
  assert.equal(document.querySelectorAll('.inquiry-client-result').length, 2)
  await act(() => document.querySelectorAll('.inquiry-client-result')[0].click())
  assert.equal(document.querySelectorAll('.inquiry-client-result')[0].getAttribute('aria-pressed'), 'true')
  await act(() => document.querySelectorAll('.inquiry-client-result')[1].click())
  assert.equal(document.querySelectorAll('.inquiry-client-result')[0].getAttribute('aria-pressed'), 'false')
  assert.equal(document.querySelectorAll('.inquiry-client-result')[1].getAttribute('aria-pressed'), 'true')
  await act(() => document.querySelector('[aria-label="Clear client search"]').click())
  assert.equal(search().value, '')
  assert.match(document.querySelector('.inquiry-selected-client').textContent, /Juan Cruz/)
  assert.equal(button("Next: Client details").disabled, false, "clear preserves the selected client")
  clientSearch = "empty"
  await searchFor("absent")
  await act(() => new Promise(resolve => setTimeout(resolve, 350)))
  assert.match(document.querySelector('#inquiry-client-search-status').textContent, /No matching clients found/)
  clientSearch = "error"
  await searchFor("failure")
  await act(() => new Promise(resolve => setTimeout(resolve, 350)))
  assert.match(document.querySelector('#inquiry-client-search-status').textContent, /Unable to load clients/)
  assert.doesNotMatch(document.querySelector('#inquiry-client-search-status').textContent, /No matching/)
  await act(() => button("Next: Client details").click())
  assert.equal(document.querySelector('[aria-label="Client name"]').value, 'Juan Cruz')
  assert.equal(document.querySelector('input[type="tel"]').value, '9123456789')
  await act(() => button("Previous").click())
  assert.match(document.querySelector('.inquiry-selected-client').textContent, /Juan Cruz/)
  await act(() => button("Cancel").click())
  assert.ok(document.querySelector('[aria-label="Save this inquiry as a draft?"]'))
})
