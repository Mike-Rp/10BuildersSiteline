import { mock } from "node:test";
import "dotenv/config";
import pg from "pg";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";
import { phaseProject, readChecklist, recordPhaseHistory } from "../src/services/progress/phase.utility.js";

const pool = new pg.Pool({
  host: process.env.DB_SERVER, database: process.env.DB_NAME, user: process.env.DB_USER,
  password: process.env.DB_PASSWORD, port: process.env.DB_PORT, connectionTimeoutMillis: 10000,
});
const client = await pool.connect();
const schema = "phase_test_" + randomUUID().replaceAll("-", "");
try {
  await client.query("BEGIN");
  await client.query(`CREATE SCHEMA "${schema}"`);
  await client.query(`SET LOCAL search_path TO "${schema}", public`);
  // Empty copies isolate fixtures, triggers, sequences, and writes from application data.
  for (const name of ["projects", "project_stages", "project_types", "project_phase_team", "project_progress_history", "users", "pending_rework_requests", "project_engineers"]) {
    await client.query(`CREATE TABLE "${schema}"."${name}" AS SELECT * FROM public."${name}" WHERE false`);
    await client.query(`ALTER TABLE "${schema}"."${name}" ADD PRIMARY KEY (id)`);
  }
  await client.query("ALTER TABLE project_progress_history ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY");
  await client.query("ALTER TABLE pending_rework_requests ALTER COLUMN id SET DEFAULT gen_random_uuid()");
  await client.query("INSERT INTO project_stages SELECT * FROM public.project_stages");
  await client.query("INSERT INTO project_types SELECT * FROM public.project_types");
  const stages = await client.query("SELECT id FROM project_stages WHERE lower(code) = 'structure'");
  assert.equal(stages.rowCount, 1, "A Structure stage must exist.");
  const stageId = stages.rows[0].id;
  const otherStage = (await client.query("SELECT id FROM project_stages WHERE id <> $1 LIMIT 1", [stageId])).rows[0].id;
  const projectId = randomUUID(), otherProjectId = randomUUID(), userId = randomUUID(), fileId = randomUUID();
  await client.query("INSERT INTO users (id, full_name) VALUES ($1, 'Test reviewer')", [userId]);
  await client.query(
    "INSERT INTO projects (id, name, project_type_id, current_stage_id, current_pct, lifecycle_status, is_deleted) VALUES ($1, 'Test Structure', (SELECT id FROM project_types LIMIT 1), $2, 62, 'active', false)",
    [projectId, stageId]);
  await client.query(
    "INSERT INTO projects (id, name, current_stage_id, lifecycle_status, is_deleted) VALUES ($1, 'Other', $2, 'active', false)",
    [otherProjectId, otherStage]);
  const migration = (await readFile(new URL("../migrations/001-phase-checklists.sql", import.meta.url), "utf8"))
    .replace(/^BEGIN;\s*/m, "").replace(/^COMMIT;\s*/m, "");
  await client.query(migration);
  const confirmationMigration = (await readFile(new URL("../migrations/002-phase-update-confirmation.sql", import.meta.url), "utf8"))
    .replace(/^BEGIN;\s*/m, "").replace(/^COMMIT;\s*/m, "");
  await client.query(confirmationMigration);
  let summary = await readChecklist(client, projectId, stageId);
  assert.equal(summary.required_count, 5);
  assert.equal(summary.pct, 0);
  assert.equal((await client.query("SELECT current_pct FROM projects WHERE id = $1", [projectId])).rows[0].current_pct, 0);
  await client.query(
    "INSERT INTO project_phase_files (id, project_id, project_stage_id, original_name, content_type, byte_size, content, uploaded_by) VALUES ($1,$2,$3,'evidence.pdf','application/pdf',9,$4,$5)",
    [fileId, projectId, stageId, Buffer.from("%PDF-test"), userId]);
  const evidence = await client.query(
    "INSERT INTO project_phase_evidence (project_id,project_stage_id,checklist_item_id,file_id,submitted_by) VALUES ($1,$2,$3,$4,$5) RETURNING id",
    [projectId, stageId, summary.items[0].id, fileId, userId]);
  summary = await readChecklist(client, projectId, stageId);
  assert.equal(summary.pct, 0, "Pending evidence must not contribute progress.");
  await client.query(
    "UPDATE project_phase_evidence SET status='approved', reviewed_by=$2, reviewed_at=now() WHERE id=$1",
    [evidence.rows[0].id, userId]);
  summary = await readChecklist(client, projectId, stageId);
  assert.equal(summary.pct, 20);
  const project = await phaseProject(client, { id: userId, role: "admin" }, projectId, { active: true });
  await recordPhaseHistory(client, project, summary.pct, "Test approval.", userId);
  assert.equal((await client.query("SELECT current_pct FROM projects WHERE id=$1", [projectId])).rows[0].current_pct, 20);
  // Migration is idempotent and cannot erase an existing approval.
  await client.query(migration);
  assert.equal((await readChecklist(client, projectId, stageId)).pct, 20);
  await client.query(
    "INSERT INTO phase_checklist_templates (project_stage_id,code,title,required,sort_order) VALUES ($1,'future_item','Future item',true,6)", [stageId]);
  assert.equal((await readChecklist(client, projectId, stageId)).required_count, 5, "Snapshots freeze checklist requirements.");

  await client.query("SAVEPOINT invalid_evidence");
  await assert.rejects(client.query(
    "INSERT INTO project_phase_evidence (project_id,project_stage_id,checklist_item_id,file_id,submitted_by) VALUES ($1,$2,$3,$4,$5)",
    [otherProjectId, otherStage, summary.items[0].id, fileId, userId]), e => e.code === "23503");
  await client.query("ROLLBACK TO SAVEPOINT invalid_evidence");

  // Verify the actual project-list SQL against PostgreSQL, including its lateral aggregates.
  const source = await readFile(new URL("../src/services/projects/read.controller.js", import.meta.url), "utf8");
  const select = source.match(/const LIST_SELECT = `([\s\S]*?)`;/)[1];
  const from = source.match(/const LIST_FROM = `([\s\S]*?)`;/)[1];
  const list = await client.query(`SELECT ${select} ${from} WHERE p.id = $1`, [projectId]);
  assert.equal(list.rows[0].current_pct, 20);
  assert.equal(list.rows[0].checklist_approved_count, 1);
  assert.equal(list.rows[0].checklist_required_count, 5);
  console.log("Database checks passed: migration/backfill, reruns, approval math, snapshots, cross-project constraints, history, project-list SQL.");

  // Exercise real controller SQL and transaction rollback in this isolated schema.
  let savepoint = 0;
  mock.module("../src/common/utilities/transaction.utility.js", {
    namedExports: { withTransaction: async callback => {
      const name = "handler_" + (++savepoint);
      await client.query("SAVEPOINT " + name);
      try {
        const result = await callback(client);
        await client.query("RELEASE SAVEPOINT " + name);
        return result;
      } catch (error) {
        await client.query("ROLLBACK TO SAVEPOINT " + name);
        throw error;
      }
    } },
  });
  const access = await import("../src/common/utilities/access.utility.js");
  mock.module("../src/common/utilities/access.utility.js", {
    namedExports: { ...access, requireUser: async (req, res, roles) => {
      if (!req.actor || (roles && !roles.includes(req.actor.role))) {
        access.sendError(res, "Forbidden.", 403); return null;
      }
      return req.actor;
    } },
  });
  const updates = await import("../src/services/progress/phase-update.controller.js");
  const phases = await import("../src/services/progress/phase.controller.js");
  const spm = { id: userId, role: "spm" }, opm = { id: userId, role: "opm" };
  await client.query("UPDATE projects SET suggested_opm_id = $2 WHERE id = $1", [projectId, userId]);
  await client.query(
    "INSERT INTO project_phase_team (id,project_id,project_stage_id,spm_user_id,status) VALUES (1,$1,$2,$3,'confirmed')",
    [projectId, stageId, userId]);
  const response = () => ({
    statusCode: 200, body: null, status(code) { this.statusCode = code; return this; },
    json(body) { this.body = body; return this; },
  });
  const request = (actor, body = {}, params = {}) => ({ actor, body, params: { id: projectId, ...params } });
  const count = async table => Number((await client.query(`SELECT count(*) AS n FROM "${table}"`)).rows[0].n);
  const historyBefore = await count("project_progress_history");
  const submit = response();
  const req = request(spm, {
    stage: "Structure", note: "Rain caused a safety stoppage.",
    issue_categories: ["weather_delay", "safety_incident"], submitted_item_ids: [summary.items[1].id],
  });
  req.file = { originalname: "report.pdf", buffer: Buffer.from("%PDF-test") };
  await updates.submitPhaseUpdate(req, submit);
  assert.equal(submit.statusCode, 201, JSON.stringify(submit.body));
  assert.equal(submit.body.data.status, "pending");
  assert.equal((await client.query("SELECT current_pct FROM projects WHERE id=$1", [projectId])).rows[0].current_pct, 20);
  assert.equal(await count("project_progress_history"), historyBefore);
  const pendingEvidence = await client.query("SELECT status,file_id FROM project_phase_evidence WHERE phase_update_id=$1", [submit.body.data.id]);
  assert.equal(pendingEvidence.rows[0].file_id, null);
  assert.equal(pendingEvidence.rows[0].status, "pending");

  const approved = response();
  await updates.approvePhaseUpdate(request(opm, {}, { updateId: submit.body.data.id }), approved);
  assert.equal(approved.statusCode, 200, JSON.stringify(approved.body));
  assert.equal(approved.body.data.current_pct, 40);
  assert.equal(await count("project_progress_history"), historyBefore + 1);
  const combined = await client.query("SELECT is_issue,issue_categories FROM project_progress_history WHERE id=$1", [approved.body.data.history_id]);
  await client.query(confirmationMigration);
  assert.equal((await client.query("SELECT entry_type FROM project_progress_history WHERE id=$1", [approved.body.data.history_id])).rows[0].entry_type, "update");
  assert.equal(combined.rows[0].is_issue, true);
  assert.deepEqual(combined.rows[0].issue_categories, ["weather_delay", "safety_incident"]);
  assert.equal((await client.query("SELECT count(*)::int AS n FROM project_phase_update_files WHERE history_id=$1", [approved.body.data.history_id])).rows[0].n, 1);
  const duplicate = response();
  await updates.approvePhaseUpdate(request(opm, {}, { updateId: submit.body.data.id }), duplicate);
  assert.equal(duplicate.statusCode, 409);

  const finishes = (await client.query("SELECT id FROM project_stages WHERE lower(code)='finishes'")).rows[0].id;
  const stageChange = response();
  await updates.submitPhaseUpdate(request(spm, { stage: "Finishes" }), stageChange);
  assert.equal(stageChange.statusCode, 201, JSON.stringify(stageChange.body));
  assert.equal((await client.query("SELECT current_stage_id FROM projects WHERE id=$1", [projectId])).rows[0].current_stage_id, stageId);
  const confirmStage = response();
  await updates.approvePhaseUpdate(request(opm, {}, { updateId: stageChange.body.data.id }), confirmStage);
  assert.equal(confirmStage.statusCode, 200, JSON.stringify(confirmStage.body));
  assert.equal(confirmStage.body.data.current_stage_id, finishes);

  const toReject = response();
  await updates.submitPhaseUpdate(request(spm, { stage: "Design", issue_categories: ["weather_delay"] }), toReject);
  const rejectedUpdate = response();
  await updates.rejectPhaseUpdate(request(opm, { resolution_note: "Please correct the stage." }, { updateId: toReject.body.data.id }), rejectedUpdate);
  assert.equal(rejectedUpdate.statusCode, 200);
  assert.equal((await client.query("SELECT current_stage_id FROM projects WHERE id=$1", [projectId])).rows[0].current_stage_id, finishes);

  const updateCount = await count("project_phase_updates"), fileCount = await count("project_phase_files");
  const invalid = request(spm, { stage: "Structure", submitted_item_ids: ["99999999"] });
  invalid.file = { originalname: "must-rollback.pdf", buffer: Buffer.from("%PDF-test") };
  const invalidResponse = response();
  await updates.submitPhaseUpdate(invalid, invalidResponse);
  assert.equal(invalidResponse.statusCode, 404);
  assert.equal(await count("project_phase_updates"), updateCount, "Invalid checklist must roll back the update.");
  assert.equal(await count("project_phase_files"), fileCount, "Invalid checklist must roll back the inline file.");

  const mark = response();
  await phases.markChecklistSubmitted(request(spm, {}, { itemId: String(summary.items[2].id) }), mark);
  assert.equal(mark.statusCode, 201, JSON.stringify(mark.body));
  assert.equal(mark.body.data.file_id, null);
  const reviewPreviousStage = response();
  await phases.approveEvidence(request(opm, {}, { evidenceId: mark.body.data.id }), reviewPreviousStage);
  assert.equal(reviewPreviousStage.statusCode, 200, JSON.stringify(reviewPreviousStage.body));
  assert.equal((await client.query("SELECT current_pct FROM projects WHERE id=$1", [projectId])).rows[0].current_pct, 0,
    "Old-stage verification must not overwrite the current stage's percentage.");
  console.log("Controller database checks passed: combined update, OPM confirmation, deferred stage change, rejection, atomic rollback, file-free submissions.");

  // Verify browser FormData reaches the combined handler through the real Express/Multer route.
  const express = (await import("express")).default;
  const { createServer } = await import("node:http");
  const router = (await import("../src/services/progress/phase.routes.js")).default;
  const app = express();
  app.use(express.json());
  app.use((req, res, next) => { req.actor = { id: userId, role: req.headers["x-test-role"] }; next(); });
  app.use("/progress", router);
  const server = createServer(app);
  await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
  try {
    const base = "http://127.0.0.1:" + server.address().port + "/progress/projects/" + projectId;
    const form = new FormData();
    form.set("payload", JSON.stringify({
      stage: "Structure", note: "Multipart report.", issue_categories: ["weather_delay"],
      submitted_item_ids: [summary.items[3].id],
    }));
    form.set("file", new Blob([Buffer.from("%PDF-test")], { type: "application/pdf" }), "multipart.pdf");
    const httpSubmit = await fetch(base + "/phase-updates", { method: "POST", headers: { "x-test-role": "spm" }, body: form });
    const httpData = await httpSubmit.json();
    assert.equal(httpSubmit.status, 201, JSON.stringify(httpData));
    assert.equal(httpData.data.status, "pending");
    assert.equal(httpData.data.file_ids.length, 1);
    assert.equal((await client.query("SELECT current_stage_id FROM projects WHERE id=$1", [projectId])).rows[0].current_stage_id, finishes);
    const httpApprove = await fetch(base + "/phase-updates/" + httpData.data.id + "/approve", {
      method: "POST", headers: { "x-test-role": "opm", "Content-Type": "application/json" }, body: "{}",
    });
    const confirmedData = await httpApprove.json();
    assert.equal(httpApprove.status, 200, JSON.stringify(confirmedData));
    assert.equal(confirmedData.data.current_stage_id, stageId);
    assert.equal(confirmedData.data.current_pct, 80);
    const overviewResponse = await fetch(base + "/phase-overview?stage=Design", { headers: { "x-test-role": "spm" } });
    const overview = await overviewResponse.json();
    assert.equal(overviewResponse.status, 200, JSON.stringify(overview));
    assert.equal(overview.data.stages.length, 7);
    assert.equal(overview.data.can_submit, true);
    assert.equal(overview.data.selected_stage, "Design");
    assert.equal(overview.data.current_stage_id, stageId);
    assert.equal(overview.data.current_pct, 80);
    console.log("HTTP checks passed: one multipart request, optional file, OPM confirmation, all-stage preview.");
  } finally {
    server.closeAllConnections();
    await new Promise(resolve => server.close(resolve));
  }


} finally {
  await client.query("ROLLBACK");
  client.release();
  await pool.end();
}
